/**
 * rest deploy
 * Generates deployment artifacts — Dockerfile and Kubernetes manifests.
 * Writes to ./deploy/ directory in the current project.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join } from 'path';

// ─── Types ────────────────────────────────────────────────────────────────────

interface DeploymentConfig {
  appName:   string;
  version:   string;
  port:      number;
  replicas?: number;
  domain?:   string;
  env?:      Record<string, string>;
}

// ─── Generator ────────────────────────────────────────────────────────────────

function generateDeployment(config: DeploymentConfig): void {
  const dir = join(process.cwd(), 'deploy');
  mkdirSync(dir, { recursive: true });

  // ── Dockerfile ──────────────────────────────────────────────────────────────
  writeFileSync(
    join(dir, 'Dockerfile'),
    `# REstJS Production Dockerfile
# Generated by: rest deploy

FROM node:20-alpine AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci
COPY . .
RUN npm run build

FROM node:20-alpine AS production
WORKDIR /app
COPY package*.json ./
RUN npm ci --production
COPY --from=builder /app/dist ./dist
EXPOSE ${config.port}
ENV NODE_ENV=production
CMD ["node", "dist/server.js"]
`
  );

  // ── Kubernetes Deployment ────────────────────────────────────────────────────
  const envVars = Object.entries(config.env || {})
    .map(([k, v]) => `        - name: ${k}\n          value: "${v}"`)
    .join('\n');

  writeFileSync(
    join(dir, 'deployment.yaml'),
    `# REstJS Kubernetes Deployment
# Generated by: rest deploy
# Apply with: kubectl apply -f deployment.yaml

apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${config.appName}
  labels:
    app: ${config.appName}
    version: "${config.version}"
spec:
  replicas: ${config.replicas || 3}
  selector:
    matchLabels:
      app: ${config.appName}
  template:
    metadata:
      labels:
        app: ${config.appName}
    spec:
      containers:
      - name: ${config.appName}
        image: ${config.appName}:${config.version}
        ports:
        - containerPort: ${config.port}
        env:
${envVars}
        livenessProbe:
          httpGet:
            path: /health/live
            port: ${config.port}
          initialDelaySeconds: 10
          periodSeconds: 30
        readinessProbe:
          httpGet:
            path: /health/ready
            port: ${config.port}
          initialDelaySeconds: 5
          periodSeconds: 10
        resources:
          requests:
            memory: "128Mi"
            cpu:    "100m"
          limits:
            memory: "512Mi"
            cpu:    "500m"
---
apiVersion: v1
kind: Service
metadata:
  name: ${config.appName}
spec:
  selector:
    app: ${config.appName}
  ports:
  - protocol: TCP
    port:       80
    targetPort: ${config.port}
  type: ClusterIP
---
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: ${config.appName}-hpa
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind:       Deployment
    name:       ${config.appName}
  minReplicas: ${config.replicas || 3}
  maxReplicas: 10
  metrics:
  - type: Resource
    resource:
      name: cpu
      target:
        type:               Utilization
        averageUtilization: 70
`
  );

  // ── Deploy Script ────────────────────────────────────────────────────────────
  writeFileSync(
    join(dir, 'deploy.sh'),
    `#!/bin/bash
# REstJS Deployment Script
# Generated by: rest deploy

set -e

APP="${config.appName}"
VERSION="${config.version}"
REGISTRY="registry.example.com"

echo "Building $APP:$VERSION..."
docker build -t $APP:$VERSION .

echo "Tagging for registry..."
docker tag $APP:$VERSION $REGISTRY/$APP:$VERSION
docker tag $APP:$VERSION $REGISTRY/$APP:latest

echo "Pushing to registry..."
docker push $REGISTRY/$APP:$VERSION
docker push $REGISTRY/$APP:latest

echo "Applying Kubernetes manifests..."
kubectl apply -f deployment.yaml

echo "Waiting for rollout..."
kubectl rollout status deployment/$APP

echo ""
echo "Deployment complete: $APP:$VERSION"
`
  );

  // Make deploy.sh executable note
  writeFileSync(
    join(dir, '.gitignore'),
    `# Deployment artifacts
*.log
`
  );
}

// ─── Command ──────────────────────────────────────────────────────────────────

/**
 * rest deploy
 * Reads package.json and generates deployment files.
 */
export async function deploy(): Promise<void> {
  console.log('\n\x1b[36m[REstJS Deploy]\x1b[0m Generating deployment artifacts...\n');

  const cwd = process.cwd();

  // Read package.json
  const pkgPath = join(cwd, 'package.json');
  if (!existsSync(pkgPath)) {
    console.error('\x1b[31mError:\x1b[0m No package.json found.');
    process.exit(1);
  }

  let pkg: any;
  try {
    pkg = JSON.parse(readFileSync(pkgPath, 'utf-8'));
  } catch {
    console.error('\x1b[31mError:\x1b[0m Could not parse package.json');
    process.exit(1);
  }

  const config: DeploymentConfig = {
    appName:  pkg.name    || 'restjs-app',
    version:  pkg.version || '1.0.0',
    port:     3000,
    replicas: 3,
    domain:   'api.example.com',
    env: {
      NODE_ENV: 'production',
      PORT:     '3000'
    }
  };

  generateDeployment(config);

  const deployDir = join(cwd, 'deploy');

  console.log('\x1b[32m✓\x1b[0m Deployment files generated:\n');
  console.log(`  \x1b[36m${deployDir}\x1b[0m`);
  console.log('  ├── Dockerfile');
  console.log('  ├── deployment.yaml   (Deployment + Service + HPA)');
  console.log('  └── deploy.sh\n');
  console.log('Next steps:\n');
  console.log('  \x1b[90m# Build production bundle\x1b[0m');
  console.log('  npm run build\n');
  console.log('  \x1b[90m# Run locally with Docker\x1b[0m');
  console.log('  docker build -t ' + config.appName + ' .');
  console.log('  docker run -p 3000:3000 ' + config.appName + '\n');
  console.log('  \x1b[90m# Deploy to Kubernetes\x1b[0m');
  console.log('  cd deploy');
  console.log('  chmod +x deploy.sh');
  console.log('  ./deploy.sh\n');
}