const FIXTURE = join(__dirname, 'fixtures', 'openapi.json')
const TSC = resolve(__dirname, '..', '..', '..', 'node_modules', 'typescript', 'bin', 'tsc')
const fixture = (): any => JSON.parse(readFileSync(FIXTURE, 'utf8'))

let dir: string
let logs: string[]

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'axil-client-'))
  logs = []
  vi.spyOn(console, 'log').mockImplementation((...a: unknown[]) => { logs.push(a.join(' ')) })
  vi.spyOn(console, 'error').mockImplementation(() => {})
})

afterEach(() => {
  vi.restoreAllMocks()
  rmSync(dir, { recursive: true, force: true })
})

/** Type-check `code` with the repo's tsc under --strict and no DOM / Node typings. */
function typeCheck(code: string): { code: number | null; out: string } {
  writeFileSync(join(dir, 'client.ts'), code)
  writeFileSync(join(dir, 'usage.ts'), USAGE)
  writeFileSync(join(dir, 'tsconfig.json'), JSON.stringify({
    compilerOptions: {
      strict: true, noEmit: true, target: 'ES2022', module: 'ES2022', moduleResolution: 'Bundler',
      lib: ['ES2022'], types: [], noUnusedLocals: true, noUnusedParameters: true, noImplicitReturns: true,
      skipLibCheck: false
    },
    include: ['client.ts', 'usage.ts']
  }))
  const r = spawnSync(process.execPath, [TSC, '-p', dir], { encoding: 'utf8', timeout: 120000 })
  return { code: r.status, out: `${r.stdout}${r.stderr}` }
}

// Exercises the generated types the way an app would (and fails tsc on regressions)
const USAGE = `
import { createApiClient, ApiError, Product, ProductStatus, UpdateProductInput } from './client'

export async function demo(): Promise<string> {
  const api = createApiClient({ baseUrl: 'http://x', token: () => 'jwt' })
  const status: ProductStatus = 'active'
  const list = await api.listProducts({ query: { page: 1, status, tag: ['a', 'b'] } })
  const first: Product | undefined = list.data?.[0]
  const one = await api.getProduct({ params: { id: 1 } })
  const created = await api.createProduct({ body: { name: 'Pen', price: 2 } })
  const patch: UpdateProductInput = { params: { id: 1 }, body: { price: null }, headers: { 'X-Request-Id': 'r' } }
  await api.updateProduct(patch)
  await api.deleteProduct({ params: { id: one.data.id } })
  const paid = await api.postOrdersByOrderIdPay({ params: { orderId: 'o1' }, body: { kind: 'cash' } })
  const health: string = await api.health()
  // @ts-expect-error path params are required
  await api.getProduct({})
  // @ts-expect-error enum values are checked
  await api.listProducts({ query: { status: 'gone' } })
  try { await api.listProducts() } catch (e) { if (e instanceof ApiError) return e.code + e.status }
  return [first?.name, created.data.status, paid.paid, health].join()
}
`

describe('generateClientSource', () => {
  it('emits types for schemas and operations', () => {
    const { code, operations, schemas, warnings } = generateClientSource(fixture(), { source: 'fixture', timestamp: '2026-01-01T00:00:00.000Z' })

    expect(warnings).toEqual([])
    expect(operations).toEqual([
      'createProduct', 'deleteProduct', 'getProduct', 'health', 'listProducts', 'postOrdersByOrderIdPay', 'updateProduct'
    ])
    // Error would shadow the global Error class
    expect(schemas).toContain('ErrorSchema')

    // Header
    expect(code.startsWith('/* eslint-disable */\n// Generated by axil generate client. Do not edit')).toBe(true)
    expect(code).toContain('// Source: fixture')
    expect(code).toContain('// Generated at: 2026-01-01T00:00:00.000Z')

    // JSON Schema → TypeScript
    expect(code).toContain('export type ProductStatus = "draft" | "active" | "archived";')
    expect(code).toContain('export interface Product {')
    expect(code).toContain('  status: ProductStatus;')
    expect(code).toContain('  description?: string | null;')          // type array with null
    expect(code).toContain('  legacyCode?: string | null;')           // OpenAPI 3.0 nullable
    expect(code).toContain('  tags?: string[];')
    expect(code).toContain('  attributes?: Record<string, string>;')  // additionalProperties
    expect(code).toContain('  "content-type"?: string;')              // quoted key
    expect(code).toContain('  /** Display name */')
    expect(code).toContain('export type ProductEnvelope = Envelope & {')   // allOf
    expect(code).toMatch(/export type Payment = \{\n {2}kind: "card";\n {2}card: string;\n\} \| \{\n {2}kind: "cash";\n\};/) // oneOf + const
    expect(code).toContain('  receipt?: string | null;')              // anyOf with null
    expect(code).toContain('export type Point = [number, number];')   // prefixItems
    expect(code).toContain('  children?: Tree[];')                    // recursive $ref
    expect(code).toContain('export type Anything = unknown;')

    // Operations
    expect(code).toContain('export interface GetProductParams {\n  /** Product id */\n  id: number;\n}')
    expect(code).toContain('export interface ListProductsInput {\n  query?: ListProductsQuery;\n}')
    expect(code).toContain('export interface CreateProductInput {\n  body: CreateProductBody;\n}')
    expect(code).toContain('  headers?: UpdateProductHeaders;')
    expect(code).toContain('export type DeleteProductResponse = void;')
    expect(code).toContain('export type HealthResponse = string;')
    expect(code).toContain('listProducts(input: ListProductsInput = {}, options?: RequestOptions): Promise<ListProductsResponse>')
    expect(code).toContain('health(options?: RequestOptions): Promise<HealthResponse>')
    expect(code).toContain('`/products/${encodePath(input.params.id)}`')
    expect(code).toMatch(/createProduct\([^)]*\)[^\n]*\n {4}return this\.request<CreateProductResponse>\("POST", "\/products", \{ body: input\.body, mediaType: "application\/json", auth: true \}/)
    expect(code).toMatch(/getProduct\([^\n]*\n[^\n]*auth: false/)
    expect(code).toContain('export class ApiError extends Error {')
    expect(code).toContain('export function createApiClient(options: ApiClientOptions = {}): ApiClient {')
    expect(code).toContain('(options.baseUrl ?? "http://localhost:3000/api")')
  })

  it('produces a file that compiles under tsc --strict', () => {
    const { code } = generateClientSource(fixture(), { timestamp: false })
    const r = typeCheck(code)
    expect(r.out).toBe('')
    expect(r.code).toBe(0)
  })

  it('is stable: the same document gives the same output, whatever the key order', () => {
    const doc = fixture()
    const shuffled = { ...doc, paths: Object.fromEntries(Object.entries(doc.paths).reverse()) }
    shuffled.components = { ...doc.components, schemas: Object.fromEntries(Object.entries(doc.components.schemas).reverse()) }
    const a = generateClientSource(doc, { timestamp: false }).code
    const b = generateClientSource(shuffled, { timestamp: false }).code
    expect(a).toBe(b)
  })

  it('honours --name and rejects documents it cannot handle', () => {
    const { code } = generateClientSource(fixture(), { name: 'ShopClient', timestamp: false })
    expect(code).toContain('export class ShopClient {')
    expect(code).toContain('export interface ShopClientOptions {')
    expect(code).toContain('export function createShopClient(')

    expect(() => generateClientSource(fixture(), { name: 'not valid' })).toThrow(/Invalid client name/)
    expect(() => generateClientSource({ swagger: '2.0' } as any)).toThrow(/Swagger 2.0/)
    expect(() => generateClientSource({} as any)).toThrow(/Not an OpenAPI 3.x document/)
  })

  it('names helpers predictably', () => {
    expect(toCamelCase('update-product')).toBe('updateProduct')
    expect(toCamelCase('Users.List_all')).toBe('usersListAll')
    expect(toPascalCase('product_status')).toBe('ProductStatus')
    expect(toPascalCase('2fa')).toBe('T2fa')
  })

  it('the generated client sends requests and throws ApiError', async () => {
    const { code } = generateClientSource(fixture(), { timestamp: false })
    // Run the generated file: it only uses erasable syntax, so Node can strip the types
    const js: string = (Module as any).stripTypeScriptTypes(code)
    // Evaluate as a function body: drop the `export` keywords and return the bindings
    const mod = new Function(`${js.replace(/^export /gm, '')}\nreturn { createApiClient, ApiError }`)()

    const calls: Array<{ url: string; init: any }> = []
    let reply: { status: number; body: string; type?: string } = { status: 200, body: '{}' }
    const fetch = async (url: string, init: any) => {
      calls.push({ url, init })
      return {
        ok: reply.status >= 200 && reply.status < 300,
        status: reply.status,
        statusText: 'Status',
        headers: { get: () => reply.type ?? 'application/json' },
        text: async () => reply.body
      }
    }
    const api = mod.createApiClient({ baseUrl: 'http://api.test/', token: async () => 'jwt-1', fetch })

    reply = { status: 200, body: JSON.stringify({ status: 200, code: 'HTTP_200_OK', message: 'ok', data: [] }) }
    const list = await api.listProducts({ query: { page: 2, tag: ['a', 'b c'], status: undefined } })
    expect(list.code).toBe('HTTP_200_OK')
    expect(calls[0].url).toBe('http://api.test/products?page=2&tag=a&tag=b%20c')
    expect(calls[0].init.method).toBe('GET')
    expect(calls[0].init.headers.authorization).toBeUndefined()

    reply = { status: 201, body: JSON.stringify({ data: { id: 7 } }) }
    await api.createProduct({ body: { name: 'Pen', price: 2 } })
    expect(calls[1].init.headers.authorization).toBe('Bearer jwt-1')
    expect(calls[1].init.headers['content-type']).toBe('application/json')
    expect(JSON.parse(calls[1].init.body)).toEqual({ name: 'Pen', price: 2 })

    reply = { status: 204, body: '' }
    expect(await api.deleteProduct({ params: { id: 'a/b' } })).toBeUndefined()
    expect(calls[2].url).toBe('http://api.test/products/a%2Fb')

    reply = { status: 404, body: JSON.stringify({ error: { code: 'NOT_FOUND', message: 'Product not found' } }) }
    const err = await api.getProduct({ params: { id: 9 } }).catch((e: unknown) => e)
    expect(err).toBeInstanceOf(mod.ApiError)
    expect(err).toMatchObject({ name: 'ApiError', status: 404, code: 'NOT_FOUND', message: 'Product not found' })

    reply = { status: 200, body: 'up', type: 'text/plain' }
    expect(await api.health()).toBe('up')
  })

  it('isGeneratedClient recognises its own header', () => {
    expect(isGeneratedClient(generateClientSource(fixture()).code)).toBe(true)
    expect(isGeneratedClient('export const x = 1\n')).toBe(false)
  })
})

describe('axil generate client', () => {
  it('reads a local file and writes src/api-client.ts', async () => {
    writeFileSync(join(dir, 'openapi.json'), readFileSync(FIXTURE))
    const r = await generateClient({ cwd: dir, from: 'openapi.json' })

    expect(r.file).toBe(join(dir, 'src', 'api-client.ts'))
    expect(r.operations).toHaveLength(7)
    const code = readFileSync(r.file, 'utf8')
    expect(code).toContain('// Source: openapi.json')
    expect(code).toMatch(/\/\/ Generated at: \d{4}-\d\d-\d\dT/)
    const out = logs.join('\n').replace(/\x1b\[[0-9;]*m/g, '')
    expect(out).toContain('7 operations')
    expect(out).toContain("import { createApiClient, ApiError } from './api-client.js'")
  })

  it('fetches from a URL, defaulting to http://localhost:<PORT>/openapi.json', async () => {
    const server: Server = createServer((req, res) => {
      if (req.url === '/openapi.json') {
        res.writeHead(200, { 'content-type': 'application/json' })
        res.end(readFileSync(FIXTURE))
      } else {
        res.writeHead(404)
        res.end()
      }
    })
    await new Promise<void>(done => server.listen(0, '127.0.0.1', done))
    const port = (server.address() as AddressInfo).port
    try {
      writeFileSync(join(dir, '.env'), `PORT=${port}\n`)
      // localhost may resolve to ::1 first; the server listens on IPv4
      const r = await generateClient({ cwd: dir, from: `http://127.0.0.1:${port}/openapi.json`, out: 'client/shop.ts', name: 'ShopClient', silent: true })
      expect(readFileSync(r.file, 'utf8')).toContain('export class ShopClient {')

      await expect(generateClient({ cwd: dir, from: `http://127.0.0.1:${port}/missing.json`, silent: true }))
        .rejects.toThrow(/answered 404/)
    } finally {
      await new Promise(done => server.close(done))
    }
  })

  it('never overwrites a hand-written file without --force', async () => {
    writeFileSync(join(dir, 'openapi.json'), readFileSync(FIXTURE))
    const target = join(dir, 'src', 'api-client.ts')
    await generateClient({ cwd: dir, from: 'openapi.json', silent: true })
    // Regenerating over a generated file is fine
    await generateClient({ cwd: dir, from: 'openapi.json', silent: true })

    writeFileSync(target, 'export const mine = true\n')
    await expect(generateClient({ cwd: dir, from: 'openapi.json', silent: true })).rejects.toThrow(/not generated by axil/)
    expect(readFileSync(target, 'utf8')).toBe('export const mine = true\n')
    await generateClient({ cwd: dir, from: 'openapi.json', force: true, silent: true })
    expect(isGeneratedClient(readFileSync(target, 'utf8'))).toBe(true)
  })

  it('explains missing, YAML and invalid documents', async () => {
    await expect(generateClient({ cwd: dir, from: 'nope.json', silent: true })).rejects.toThrow(/not found/)
    writeFileSync(join(dir, 'api.yaml'), 'openapi: 3.1.0\ninfo:\n  title: x\n')
    await expect(generateClient({ cwd: dir, from: 'api.yaml', silent: true })).rejects.toThrow(/looks like YAML/)
    writeFileSync(join(dir, 'bad.json'), '{"openapi": "2.0"}')
    await expect(generateClient({ cwd: dir, from: 'bad.json', silent: true })).rejects.toThrow(/Not an OpenAPI 3.x/)
    expect(existsSync(join(dir, 'src', 'api-client.ts'))).toBe(false)
  })
})
