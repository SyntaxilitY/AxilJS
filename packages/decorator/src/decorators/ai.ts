/**
 * AI semantic decorators — provider-independent.
 */

import { defineDecorator } from '../core/define'
import { registerMetadata } from '../core/registry'
import type { TDecoratorFunction } from '../core/types'

// ── tAIComplete ────────────────────────────────────────────────────────

export interface TAICompleteOptions {
  task?: 'summarization' | 'classification' | 'extraction' | 'generation' | 'reasoning'
  systemPrompt?: string
  temperature?: number
  maxTokens?: number
}

export const tAIComplete = (options: TAICompleteOptions = {}): TDecoratorFunction =>
  defineDecorator(
    {
      name: 'tAIComplete',
      description: 'Auto-completion via an LLM',
      purpose: 'Marks the method as producing its result through LLM completion',
      why: 'Provider-independent AI declarations decouple app code from vendors',
      whenToUse: 'On methods whose output is generated by an LLM',
      category: 'AI',
      targets: ['method'],
      consumedBy: ['@axiljs/ai'],
      composesWith: ['tAIModel', 'tAITokenBudget', 'tAIGuard', 'tCache'],
      examples: ['@tAIComplete({ task: "summarization" })']
    },
    (target, propertyKey) => {
      registerMetadata('tAIComplete', target, propertyKey, options)
    }
  )

