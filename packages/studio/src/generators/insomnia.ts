/**
 * Generates Insomnia Collection from discovered routes.
 */

import type { RouteInfo } from '../types.js'
import { randomUUID } from 'crypto'

export function generateInsomniaCollection(
  appName: string,
  appUrl:  string,
  routes:  RouteInfo[]
): object {
  const workspaceId = `wrk_${randomUUID().replace(/-/g, '').slice(0, 16)}`
  const envId       = `env_${randomUUID().replace(/-/g, '').slice(0, 16)}`

  const resources: object[] = [
    {
      _id:         workspaceId,
      _type:       'workspace',
      name:        `${appName} API`,
      description: 'Generated by AxilJS Studio',
      scope:       'collection'
    },
    {
      _id:          envId,
      _type:        'environment',
      parentId:     workspaceId,
      name:         'Development',
      data:         { baseUrl: appUrl, token: '' },
      dataPropertyOrder: { '&': ['baseUrl', 'token'] }
    }
  ]

  for (const route of routes) {
    const reqId = `req_${randomUUID().replace(/-/g, '').slice(0, 16)}`

    const request: Record<string, unknown> = {
      _id:          reqId,
      _type:        'request',
      parentId:     workspaceId,
      name:         `${route.method} ${route.path}`,
      method:       route.method,
      url:          `{{ _.baseUrl }}${route.path}`,
      headers:      [
        { name: 'Content-Type', value: 'application/json' }
      ],
      authentication: {
        type:   'bearer',
        token:  '{{ _.token }}',
        disabled: true
      }
    }

    if (['POST', 'PUT', 'PATCH'].includes(route.method)) {
      request.body = {
        mimeType: 'application/json',
        text:     JSON.stringify({ key: 'value' }, null, 2)
      }
    }

    resources.push(request)
  }

  return {
    _type:      'export',
    __export_format: 4,
    __export_date:   new Date().toISOString(),
    __export_source: 'axiljs-studio',
    resources
  }
}